import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { parseEnv } from 'node:util';

const files = ['../plugin/features/quality.js', '../plugin/features/pro-design.js', '../plugin/features/game-ui.js',
  '../plugin/features/game-localization.js', '../plugin/features/game-previews.js', '../plugin/features/game-widgets.js', '../plugin/features/game-packaging.js', '../plugin/core.js'];
const code = '// Generated by npm run build. Edit plugin/core.js or plugin/features/*.js.\n' +
  files.map(file => readFileSync(new URL(file, import.meta.url), 'utf8')).join('\n');
writeFileSync(new URL('../plugin/code.js', import.meta.url), code);
const envPath = new URL('../.env', import.meta.url);
const env = existsSync(envPath) ? parseEnv(readFileSync(envPath, 'utf8')) : {};
const port = Number(env.FIGMA_BRIDGE_PORT || 3055);
const token = env.FIGMA_BRIDGE_TOKEN;
const config = typeof token === 'string' && token.length >= 32 && token.length <= 1000 && Number.isInteger(port) && port > 0 && port <= 65535
  ? { port, ports: [...new Set([port, 3055, 3056, 3057])], token } : null;
const html = readFileSync(new URL('../plugin/ui.html', import.meta.url), 'utf8');
// Escape HTML delimiters because this local credential is inserted into a script element.
writeFileSync(new URL('../plugin/ui.local.html', import.meta.url),
  html.replace('/* LOCAL_CONNECTION */ null', JSON.stringify(config).replace(/</g, '\\u003c')),
  { mode: 0o600 });
